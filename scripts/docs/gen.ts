// Generates docs/ROUTES.md, docs/DATA_MODEL.md, docs/DEPENDENCIES.md from the code, DB and lockfile.
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import pg from 'pg';

const root = process.cwd();
function walk(d: string, out: string[] = []) {
  for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p, out) : out.push(p); }
  return out;
}
const urlOf = (file: string, base: string) => (p => p === '' ? '/' : p)(
  '/' + relative(base, file).replace(/\/?(route|page)\.tsx?$/, '').replace(/\\/g, '/').replace(/\/\([^)]*\)/g, ''));

// ---- routes
const app = join(root, 'src/app');
const rows: string[] = [];
for (const f of walk(app).sort()) {
  if (/\/route\.ts$/.test(f)) {
    const src = readFileSync(f, 'utf8');
    const methods = ['GET','POST','PUT','PATCH','DELETE'].filter(m => new RegExp(`export (const|async function) ${m}\\b`).test(src));
    const pub = /public:\s*true/.test(src) ? 'public' : /allowEnrolOnly/.test(src) ? 'session (enrol-only ok)' : 'session + membership';
    rows.push(`| API | \`${urlOf(f, app)}\` | ${methods.join(', ') || '?'} | ${pub} |`);
  } else if (/\/page\.tsx$/.test(f)) {
    rows.push(`| Page | \`${urlOf(f, app)}\` | GET | see page |`);
  }
}
writeFileSync(join(root, 'docs/ROUTES.md'),
`# Route inventory

Generated by \`npx tsx scripts/docs/gen.ts\` from src/app. Access column for APIs is read from the handler options;
the policy check (role and tenant) happens inside each handler through src/server/policy.ts, which is deny by default.

| Kind | Path | Methods | Auth |
|---|---|---|---|
${rows.join('\n')}
`);

// ---- dependencies
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const pkgJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const direct = new Set([...Object.keys(pkgJson.dependencies), ...Object.keys(pkgJson.devDependencies)]);
const lines: string[] = [];
const counts: Record<string, number> = {};
const review: string[] = [];
for (const [k, v] of Object.entries<any>(lock.packages)) {
  if (!k) continue;
  const name = k.replace(/^.*node_modules\//, '');
  const pj = join(root, k, 'package.json');
  let lic = v.license || (existsSync(pj) ? JSON.parse(readFileSync(pj, 'utf8')).license : undefined) || 'UNKNOWN';
  if (typeof lic === 'object') lic = lic.type;
  counts[lic] = (counts[lic] || 0) + 1;
  if (/GPL|LGPL|AGPL|MPL|UNKNOWN|CC-BY|SSPL|BUSL/i.test(String(lic))) review.push(`| ${name} | ${v.version} | ${lic} | ${v.dev ? 'dev' : 'runtime'} |`);
  if (direct.has(name)) lines.push(`| ${name} | ${v.version} | ${lic} | ${v.dev ? 'dev' : 'runtime'} |`);
}
writeFileSync(join(root, 'docs/DEPENDENCIES.md'),
`# Dependencies and licences

Generated from package-lock.json and each package's own package.json. This is an inventory, not legal advice;
licence terms must be reviewed by the client's counsel before commercial hand-over.

## Direct dependencies
| Package | Version | Licence | Used in |
|---|---|---|---|
${lines.sort().join('\n')}

## Licence counts (all ${Object.values(counts).reduce((a,b)=>a+b,0)} installed packages)
${Object.entries(counts).sort((a,b)=>b[1]-a[1]).map(([l,c])=>`- ${l}: ${c}`).join('\n')}

## Needs a human licence review (copyleft, weak copyleft, unknown)
| Package | Version | Licence | Used in |
|---|---|---|---|
${review.sort().join('\n') || '| none found | | | |'}

Not in the npm inventory (installed in the Docker image or bundled as files):

| Item | Licence / status | Used for |
|---|---|---|
| opencv-contrib-python-headless 4.10.0.84 (pip) | Apache-2.0 per its package metadata; not verified against upstream | image enhancement (dnn_superres) |
| numpy (pip) | BSD-3-Clause per package metadata; not verified | dependency of OpenCV |
| ESPCN_x2.pb, ESPCN_x4.pb (assets/models) | origin: supplied inside the PrintForge Preflight MVP; the licence of the trained model files has NOT been verified | enhancement models |
| FOGRA39.icc (assets/profiles) | the file says "free of known copyright restrictions"; not legally reviewed; client has not confirmed FOGRA39 | CMYK export |
| DejaVu Sans (Debian fonts-dejavu-core) | free font licence (Bitstream Vera / public domain changes) per Debian; not verified | watermark text |
| python3 | PSF licence | runs the enhancement script |

Ghostscript is NOT used (CMYK is done with libvips/lcms and our own file writers), so its AGPL terms do not apply.

Notes: sharp bundles libvips as a separate native package (licence shown above if LGPL); it is dynamically linked, but
the client should confirm this satisfies their distribution model. Licence fields come from package metadata and were
not verified against upstream licence files.
`);

// ---- data model from the live schema
const c = new pg.Client({ connectionString: process.env.DATABASE_URL || 'postgres://artwork:artwork_dev@localhost:5432/artwork_dev' });
await c.connect();
const cols = await c.query(`select table_name, column_name, data_type, is_nullable from information_schema.columns where table_schema='public' order by table_name, ordinal_position`);
const fks = await c.query(`select tc.table_name, kcu.column_name, ccu.table_name ref from information_schema.table_constraints tc
 join information_schema.key_column_usage kcu using (constraint_name, table_schema)
 join information_schema.constraint_column_usage ccu using (constraint_name, table_schema)
 where tc.constraint_type='FOREIGN KEY' and tc.table_schema='public'`);
const by: Record<string, string[]> = {};
for (const r of cols.rows) (by[r.table_name] ||= []).push(`${r.column_name} ${r.data_type}${r.is_nullable === 'NO' ? ' not null' : ''}`);
const fkBy: Record<string, string[]> = {};
for (const r of fks.rows) (fkBy[r.table_name] ||= []).push(`${r.column_name} -> ${r.ref}`);
const out = Object.keys(by).sort().map(t => `### ${t}\n${by[t].map(x => `- ${x}`).join('\n')}${fkBy[t] ? `\n- references: ${fkBy[t].join('; ')}` : ''}`).join('\n\n');
writeFileSync(join(root, 'docs/DATA_MODEL.md'), `# Data model\n\nGenerated from the migrated development database (${Object.keys(by).length} tables). Migrations in /migrations are the source of truth.\n\n${out}\n`);
await c.end();
console.log('ok', rows.length, 'routes', Object.keys(by).length, 'tables');
